const {chromium}=require('../.tools/browser/node_modules/playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
(async()=>{
 const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe'});
 const page=await browser.newPage({viewport:{width:390,height:844}});
 await page.route('**/vendor/**',route=>route.abort());
 await page.goto('http://127.0.0.1:4173/#projects',{waitUntil:'networkidle'});
 assert.equal(await page.locator('#projects').isVisible(),true);
 await page.locator('[data-detail="regcrim"]').click();
 assert.equal(await page.locator('dialog[open] h2').innerText(),'REGCRIM');
 await page.keyboard.press('Escape');
 await page.locator('.lang').click();
 assert.equal(await page.locator('html').getAttribute('lang'),'en');
 await page.unroute('**/vendor/**');
 await page.goto('http://127.0.0.1:4173',{waitUntil:'networkidle'});
 await page.emulateMedia({reducedMotion:'reduce'});
 await page.waitForFunction(()=>ScrollTrigger.getAll().length===0);
 assert.equal(await page.evaluate(()=>ScrollTrigger.getAll().length),0);
 await page.emulateMedia({reducedMotion:'no-preference'});
 await page.waitForFunction(()=>ScrollTrigger.getAll().length>0);
 assert.equal(await page.evaluate(()=>ScrollTrigger.getAll().length>0),true);
 await page.goto('http://127.0.0.1:4173/og-image.svg');
 await page.setViewportSize({width:1200,height:630});
 await page.screenshot({path:'og-image.png'});
 console.log('PASS: GSAP unavailable; deep link; dialogs and language fallback; live reduced-motion changes; social image exported.');
 fs.writeFileSync('artifacts/fallback-results.txt','PASS: GSAP unavailable; deep link; dialogs and language fallback; live reduced-motion changes.\n');
 await browser.close();
})().catch(error=>{console.error(error);process.exit(1)});
